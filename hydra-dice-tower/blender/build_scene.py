"""
Blender scene builder for the Baby Hydra Dice Tower.

Run with Blender (4.2+ / 5.x):
    blender --background --python build_scene.py -- --render
or with the standalone `bpy` Python module:
    python build_scene.py --render

What it does
  * imports every printable part (coloured .ply if present, else the .stl)
  * places them using stl/assembly.json (parts are stored in PRINT pose)
  * builds collections: Assembled, Exploded, Cutaway (ghost body + glowing dice
    paths), Section (true cut at x = 0), PrintPlates (parts as they sit on the bed)
  * optionally renders preview images into ../renders
  * saves hydra_dice_tower.blend next to this script

The geometry itself is generated by ../generator/build_parts.py (signed
distance fields + marching cubes) because that route always yields watertight,
manifold meshes; Blender is used for assembly, inspection and rendering.
"""
import json
import math
import os
import sys

import bpy
import mathutils

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
STL = os.path.join(ROOT, 'stl')
PLY = os.path.join(HERE, 'parts_colored')
RENDERS = os.path.join(ROOT, 'renders')
PARTS = ['body', 'neck_center', 'neck_left', 'neck_right', 'tray']

argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
DO_RENDER = '--render' in argv
SAMPLES = 96 if '--hq' in argv else 40
DECIMATE_SAVE = 0.35        # keep the saved .blend a reasonable size
ONLY = argv[argv.index('--views') + 1].split(',') if '--views' in argv else None   # e.g. --views print_layout
SAVE = '--no-save' not in argv


def M(m):
    return mathutils.Matrix(m)


def new_collection(name):
    c = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(c)
    return c


def material_vertex_color(name, alpha=1.0, rough=0.55):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = nt.nodes['Principled BSDF']
    attr = nt.nodes.new('ShaderNodeVertexColor')
    attr.layer_name = 'Col'
    nt.links.new(attr.outputs['Color'], bsdf.inputs['Base Color'])
    bsdf.inputs['Roughness'].default_value = rough
    if alpha < 1:
        bsdf.inputs['Alpha'].default_value = alpha
        try:
            mat.surface_render_method = 'BLENDED'
        except Exception:
            pass
    return mat


def material_flat(name, rgb, rough=0.5, emission=0.0, alpha=1.0):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    b = mat.node_tree.nodes['Principled BSDF']
    b.inputs['Base Color'].default_value = (*rgb, 1)
    b.inputs['Roughness'].default_value = rough
    if emission:
        b.inputs['Emission Color'].default_value = (*rgb, 1)
        b.inputs['Emission Strength'].default_value = emission
    if alpha < 1:
        b.inputs['Alpha'].default_value = alpha
    return mat


def import_part(name):
    ply = os.path.join(PLY, f'{name}.ply')
    if os.path.exists(ply):
        bpy.ops.wm.ply_import(filepath=ply)
    else:
        bpy.ops.wm.stl_import(filepath=os.path.join(STL, f'{name}.stl'))
    ob = bpy.context.selected_objects[0]
    ob.name = name
    for c in ob.users_collection:
        c.objects.unlink(ob)
    return ob


def link(ob, coll):
    coll.objects.link(ob)
    return ob


def duplicate(ob, coll, name):
    d = ob.copy()
    d.data = ob.data
    d.name = name
    coll.objects.link(d)
    return d


def add_curve(points, coll, name, radius, mat):
    cu = bpy.data.curves.new(name, 'CURVE')
    cu.dimensions = '3D'
    sp = cu.splines.new('POLY')
    sp.points.add(len(points) - 1)
    for p, q in zip(sp.points, points):
        p.co = (*q, 1)
    cu.bevel_depth = radius
    cu.bevel_resolution = 4
    ob = bpy.data.objects.new(name, cu)
    ob.data.materials.append(mat)
    coll.objects.link(ob)
    return ob


def add_die(coll, kind, loc, size, rgb, rot=(0.3, 0.5, 0.2)):
    if kind == 'd20':
        bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=1, radius=size / 2, location=loc)
    else:
        bpy.ops.mesh.primitive_cube_add(size=size, location=loc)
        bev = bpy.context.object.modifiers.new('bev', 'BEVEL')
        bev.width = size * 0.12
        bev.segments = 3
    ob = bpy.context.object
    ob.rotation_euler = rot
    ob.name = f'prop_{kind}'
    for c in ob.users_collection:
        c.objects.unlink(ob)
    coll.objects.link(ob)
    ob.data.materials.append(material_flat(f'mat_{kind}', rgb, rough=0.25))
    return ob


def setup_world_and_render():
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    sc.cycles.device = 'CPU'
    sc.cycles.samples = SAMPLES
    try:
        sc.cycles.use_denoising = True
    except Exception:
        pass
    sc.render.resolution_x = 1400
    sc.render.resolution_y = 1100
    sc.render.film_transparent = False
    sc.view_settings.view_transform = 'AgX' if 'AgX' in [i.identifier for i in sc.view_settings.bl_rna.properties['view_transform'].enum_items] else 'Filmic'
    w = bpy.data.worlds.new('World')
    sc.world = w
    w.use_nodes = True
    bg = w.node_tree.nodes['Background']
    bg.inputs[0].default_value = (0.93, 0.89, 0.86, 1)
    bg.inputs[1].default_value = 0.55
    # lights
    def area(name, loc, energy, size, rgb=(1, 0.97, 0.92)):
        l = bpy.data.lights.new(name, 'AREA')
        l.energy = energy
        l.size = size
        l.color = rgb
        o = bpy.data.objects.new(name, l)
        o.location = loc
        o.rotation_euler = (mathutils.Vector((0, -20, 90)) - mathutils.Vector(loc)).to_track_quat('-Z', 'Y').to_euler()
        sc.collection.objects.link(o)
    area('Key', (260, 380, 420), 9.0e6 * 0.03, 260)
    area('Fill', (-420, 160, 220), 3.0e6 * 0.03, 300, (0.9, 0.92, 1.0))
    area('Rim', (-120, -420, 360), 5.0e6 * 0.03, 220)
    # table
    bpy.ops.mesh.primitive_plane_add(size=1400, location=(0, 0, -0.05))
    tb = bpy.context.object
    tb.name = 'Table'
    tb.data.materials.append(material_flat('table', (0.42, 0.27, 0.17), rough=0.45))
    cam = bpy.data.cameras.new('Camera')
    cam.lens = 60
    co = bpy.data.objects.new('Camera', cam)
    sc.collection.objects.link(co)
    sc.camera = co
    return sc, co


def look(co, loc, target):
    co.location = loc
    co.rotation_euler = (mathutils.Vector(target) - mathutils.Vector(loc)).to_track_quat('-Z', 'Y').to_euler()


def show_only(*colls):
    for c in bpy.context.scene.collection.children:
        c.hide_render = c.name not in colls
        c.hide_viewport = c.name not in colls


def render(sc, name):
    if ONLY and name[:-4] not in ONLY:
        return
    os.makedirs(RENDERS, exist_ok=True)
    sc.render.filepath = os.path.join(RENDERS, name)
    bpy.ops.render.render(write_still=True)
    print('rendered', name)


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    with open(os.path.join(STL, 'assembly.json')) as f:
        asm = json.load(f)
    paths = json.load(open(os.path.join(STL, 'dice_paths.json')))
    sc, cam = setup_world_and_render()

    c_asm = new_collection('Assembled')
    c_exp = new_collection('Exploded')
    c_cut = new_collection('Cutaway')
    c_sec = new_collection('Section')
    c_plate = new_collection('PrintPlates')

    mat = material_vertex_color('hydra_paint')
    ghost = material_vertex_color('hydra_ghost', alpha=0.22, rough=0.3)
    glow = material_flat('dice_path', (0.72, 0.35, 1.0), emission=6.0)
    src = {}
    for name in PARTS:
        ob = import_part(name)
        ob.data.materials.append(mat)
        src[name] = ob
        link(ob, c_plate)                       # print pose
    # print-plate layout: spread them out on the "bed"
    offs = {'body': (0, 0), 'neck_center': (190, 0), 'neck_left': (300, 0), 'neck_right': (410, 0), 'tray': (0, -170)}
    for n, (x, y) in offs.items():
        src[n].location = (x, y, 0)

    for name in PARTS:
        a = duplicate(src[name], c_asm, f'{name}_assembled')
        a.location = (0, 0, 0)
        a.matrix_world = M(asm[name])
        e = duplicate(src[name], c_exp, f'{name}_exploded')
        e.location = (0, 0, 0)
        Mx = mathutils.Matrix(asm[name])
        if name.startswith('neck'):
            axis = mathutils.Vector((Mx[0][2], Mx[1][2], Mx[2][2]))
            Mx = mathutils.Matrix.Translation(axis * 55) @ Mx
        if name == 'tray':
            Mx = mathutils.Matrix.Translation((0, -55, 0)) @ Mx
        e.matrix_world = Mx
        g = duplicate(src[name], c_cut, f'{name}_ghost')
        g.location = (0, 0, 0)
        g.matrix_world = M(asm[name])
        g.data = src[name].data.copy()
        g.data.materials.clear()
        g.data.materials.append(ghost)
    for k, pts in paths.items():
        add_curve(pts, c_cut, f'path_{k}', 2.2, glow)

    # true section at x = 0 (keep the -X half) using a boolean cutter
    bpy.ops.mesh.primitive_cube_add(size=1)
    cutter = bpy.context.object
    cutter.name = 'section_cutter'
    cutter.scale = (300, 600, 600)
    cutter.location = (150, 0, 100)
    cutter.hide_render = True
    cutter.hide_viewport = True
    for name in PARTS:
        s = duplicate(src[name], c_sec, f'{name}_section')
        s.location = (0, 0, 0)
        s.matrix_world = M(asm[name])
        mod = s.modifiers.new('section', 'BOOLEAN')
        mod.object = cutter
        mod.operation = 'DIFFERENCE'
        for solver in ('MANIFOLD', 'EXACT'):
            try:
                mod.solver = solver
                break
            except Exception:
                continue
    for k, pts in paths.items():
        if k == 'center':
            add_curve(pts, c_sec, 'section_path_center', 2.0, glow)

    # props: dice like the reference picture
    for coll in (c_asm,):
        nk = paths['center']
        add_die(coll, 'd20', (paths['center'][0][0], paths['center'][0][1] + 4, paths['center'][0][2] + 32), 24, (0.42, 0.12, 0.62))
        tray_c = mathutils.Matrix(asm['tray']).to_translation()
        add_die(coll, 'd20', (tray_c.x + 8, tray_c.y + 6, 14.5), 24, (0.75, 0.06, 0.08), rot=(0.9, 0.2, 0.4))
        add_die(coll, 'd6', (95, 60, 8.0), 16, (0.95, 0.92, 0.82), rot=(0, 0, 0.5))
        add_die(coll, 'd20', (-100, 70, 11.0), 22, (0.10, 0.30, 0.60), rot=(0.3, 0.1, 0.9))

    if DO_RENDER:
        T = (0, -10, 95)
        show_only('Assembled')
        look(cam, (330, 470, 250), T); render(sc, 'assembled_front_3q.png')
        look(cam, (0, 560, 140), T); render(sc, 'assembled_front.png')
        look(cam, (-300, -470, 250), (0, -40, 70)); render(sc, 'assembled_rear_3q.png')
        look(cam, (580, -60, 150), T); render(sc, 'assembled_side.png')
        show_only('Exploded')
        look(cam, (420, 520, 330), (0, -20, 110)); render(sc, 'exploded.png')
        show_only('Cutaway')
        look(cam, (60, 560, 170), T); render(sc, 'cutaway_paths_front.png')
        look(cam, (520, 260, 230), T); render(sc, 'cutaway_paths_3q.png')
        show_only('Section')
        look(cam, (560, 0, 110), (0, -15, 95)); render(sc, 'section_x0.png')
        show_only('PrintPlates')
        cam.data.lens = 35
        look(cam, (205, -470, 520), (205, -70, 20)); render(sc, 'print_layout.png')
        cam.data.lens = 60

    # lighter meshes for the saved .blend (the STLs stay full resolution)
    dg = bpy.context.evaluated_depsgraph_get()
    for name, ob in src.items():
        meshes = {ob.data.name}
        if len(ob.data.polygons) <= 200_000:
            continue
        d = ob.modifiers.new('save_decimate', 'DECIMATE')
        d.ratio = DECIMATE_SAVE
        dg.update()
        light = bpy.data.meshes.new_from_object(ob.evaluated_get(dg))
        ob.modifiers.remove(d)
        old_mesh = ob.data
        for o in bpy.data.objects:
            if o.type == 'MESH' and o.data == old_mesh:
                o.data = light
        light.name = name
    for o in bpy.data.objects:
        if o.name.endswith('_ghost') and len(o.data.polygons) > 200_000:
            base = src[o.name[:-6]].data.copy()
            base.materials.clear()
            base.materials.append(ghost)
            o.data = base
    show_only('Assembled', 'Exploded', 'Cutaway', 'Section', 'PrintPlates')
    for c in bpy.context.scene.collection.children:
        c.hide_viewport = c.name != 'Assembled'
    if not SAVE:
        return
    out = os.path.join(HERE, 'hydra_dice_tower.blend')
    bpy.ops.wm.save_as_mainfile(filepath=out, compress=True)
    print('saved', out)


main()
